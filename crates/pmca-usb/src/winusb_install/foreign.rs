//! Driver packages other tools left for Sony devices.
//!
//! Zadig, which the original Sony-PMCA-RE asked users to run, generates a
//! driver package per device with libwdi and leaves it in the driver store for
//! good. Windows then hands that package to the camera on its own the moment
//! the device appears — before this program can assign WinUSB — so a
//! service-mode switch meets libusb0 first and the reassignment that follows
//! can fail to start the device. A package on a mass-storage product id is
//! worse: the camera is no longer a drive at all.
//!
//! Detection reads the driver database in the registry, which needs no
//! administrator rights. Removal does, and it never takes names from the
//! caller: [`remove_foreign`] finds the packages again itself, so the elevated
//! helper cannot be talked into deleting anything else.

use std::collections::BTreeMap;

use windows::Win32::Foundation::ERROR_SUCCESS;
use windows::Win32::System::Registry::{
    HKEY, HKEY_LOCAL_MACHINE, KEY_READ, REG_VALUE_TYPE, RRF_RT_REG_MULTI_SZ, RRF_RT_REG_SZ,
    RegCloseKey, RegEnumKeyExW, RegEnumValueW, RegGetValueW, RegOpenKeyExW,
};
use windows::core::{PCWSTR, PWSTR};

use super::{Cleanup, Result, setup, wide};

/// Hardware ids Windows has a driver for, one key per id, one value per INF.
const DEVICE_IDS: &str = r"SYSTEM\DriverDatabase\DeviceIds\USB";
/// Published INF name to the package it belongs to.
const INF_FILES: &str = r"SYSTEM\DriverDatabase\DriverInfFiles";
/// Package name to provider and signer.
const PACKAGES: &str = r"SYSTEM\DriverDatabase\DriverPackages";

/// Sony's vendor id as it appears in a driver database key name.
const SONY: &str = "VID_054C&";

/// A driver package another tool generated for a Sony device.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ForeignPackage {
    /// Published name in the driver store, `oem<n>.inf`.
    pub published: String,
    /// Provider named in the INF, e.g. `libusb-win32`, `libusbK` or `libwdi`.
    pub provider: String,
    /// The Sony hardware ids it claims, e.g. `USB\VID_054C&PID_0336`.
    pub devices: Vec<String>,
}

/// Every libwdi-generated package that claims a Sony device.
pub fn foreign_packages() -> Vec<ForeignPackage> {
    sony_packages()
        .into_iter()
        .filter(|(package, signer)| is_libwdi(&package.provider, signer))
        .map(|(package, _)| package)
        .collect()
}

/// Every third-party package that claims a Sony device, with its signer.
fn sony_packages() -> Vec<(ForeignPackage, String)> {
    let Some(usb) = Key::open(DEVICE_IDS) else { return Vec::new() };
    let mut claims: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for id in usb.subkeys() {
        if !id.to_ascii_uppercase().starts_with(SONY) {
            continue;
        }
        let Some(key) = Key::open(&format!(r"{DEVICE_IDS}\{id}")) else { continue };
        for inf in key.value_names() {
            let inf = inf.to_ascii_lowercase();
            if is_published_name(&inf) {
                claims.entry(inf).or_default().push(format!(r"USB\{}", id.to_ascii_uppercase()));
            }
        }
    }

    claims
        .into_iter()
        .filter_map(|(published, devices)| {
            let package = Key::open(&format!(r"{INF_FILES}\{published}"))?.string("Active")?;
            let details = Key::open(&format!(r"{PACKAGES}\{package}"))?;
            let provider = details.string("Provider").unwrap_or_default();
            let signer = details.string("SignerName").unwrap_or_default();
            Some((ForeignPackage { published, provider, devices }, signer))
        })
        .collect()
}

/// Remove every package [`foreign_packages`] reports, returning the devices
/// to the drivers Windows ships. Needs administrator rights.
///
/// A package that cannot be removed is skipped rather than ending the pass;
/// the caller sees it in the next [`foreign_packages`].
pub fn remove_foreign() -> Result<Cleanup> {
    let mut cleanup = Cleanup::default();
    let mut first_error = None;
    for package in foreign_packages() {
        match setup::remove_package(&package.published) {
            Ok(()) => cleanup.packages.push(package.published),
            Err(e) => {
                first_error.get_or_insert(e);
            }
        }
    }
    if !cleanup.packages.is_empty() {
        setup::rescan_devices();
    }
    match first_error {
        Some(e) if cleanup.packages.is_empty() => Err(e),
        _ => Ok(cleanup),
    }
}

/// libwdi signs every package it generates with a certificate of its own,
/// named after the device and marked "(libwdi autogenerated)". Packages of
/// other origin — Sony's own, Microsoft's, ours — never carry that mark.
fn is_libwdi(provider: &str, signer: &str) -> bool {
    signer.to_ascii_lowercase().contains("libwdi") || provider.eq_ignore_ascii_case("libwdi")
}

/// `oem<n>.inf`: the names Windows gives third-party packages. In-box INFs
/// such as `usbstor.inf` are never candidates.
fn is_published_name(name: &str) -> bool {
    name.strip_prefix("oem")
        .and_then(|rest| rest.strip_suffix(".inf"))
        .is_some_and(|n| !n.is_empty() && n.bytes().all(|b| b.is_ascii_digit()))
}

/// An open registry key below `HKEY_LOCAL_MACHINE`, closed on drop.
struct Key(HKEY);

impl Key {
    fn open(path: &str) -> Option<Self> {
        let path = wide(path);
        let mut key = HKEY::default();
        // SAFETY: `path` outlives the call; `key` receives the handle.
        let status = unsafe {
            RegOpenKeyExW(HKEY_LOCAL_MACHINE, PCWSTR(path.as_ptr()), None, KEY_READ, &mut key)
        };
        (status == ERROR_SUCCESS).then_some(Self(key))
    }

    fn subkeys(&self) -> Vec<String> {
        let mut names = Vec::new();
        let mut buffer = [0u16; 256];
        for index in 0.. {
            let mut length = buffer.len() as u32;
            // SAFETY: `buffer` and `length` describe the same writable memory.
            let status = unsafe {
                RegEnumKeyExW(
                    self.0,
                    index,
                    Some(PWSTR(buffer.as_mut_ptr())),
                    &mut length,
                    None,
                    None,
                    None,
                    None,
                )
            };
            // The end of the list, or a name too long for any id we look for.
            if status != ERROR_SUCCESS {
                break;
            }
            names.push(String::from_utf16_lossy(&buffer[..length as usize]));
        }
        names
    }

    fn value_names(&self) -> Vec<String> {
        let mut names = Vec::new();
        let mut buffer = [0u16; 256];
        for index in 0.. {
            let mut length = buffer.len() as u32;
            // SAFETY: `buffer` and `length` describe the same writable memory;
            // the data itself is not requested.
            let status = unsafe {
                RegEnumValueW(
                    self.0,
                    index,
                    Some(PWSTR(buffer.as_mut_ptr())),
                    &mut length,
                    None,
                    None,
                    None,
                    None,
                )
            };
            if status != ERROR_SUCCESS {
                break;
            }
            names.push(String::from_utf16_lossy(&buffer[..length as usize]));
        }
        names
    }

    /// A string value; of a multi-string, its first entry.
    fn string(&self, name: &str) -> Option<String> {
        let name = wide(name);
        let mut buffer = [0u16; 512];
        let mut size = (buffer.len() * 2) as u32;
        let mut kind = REG_VALUE_TYPE::default();
        // SAFETY: `buffer` holds `size` bytes; `name` outlives the call.
        let status = unsafe {
            RegGetValueW(
                self.0,
                PCWSTR::null(),
                PCWSTR(name.as_ptr()),
                RRF_RT_REG_SZ | RRF_RT_REG_MULTI_SZ,
                Some(&mut kind),
                Some(buffer.as_mut_ptr().cast()),
                Some(&mut size),
            )
        };
        if status != ERROR_SUCCESS {
            return None;
        }
        let units = &buffer[..(size as usize / 2).min(buffer.len())];
        let first = units.split(|&c| c == 0).next().unwrap_or_default();
        (!first.is_empty()).then(|| String::from_utf16_lossy(first))
    }
}

impl Drop for Key {
    fn drop(&mut self) {
        // SAFETY: the handle came from `RegOpenKeyExW` and is closed once.
        unsafe {
            let _ = RegCloseKey(self.0);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn zadig_packages_are_recognised_by_their_signer() {
        assert!(is_libwdi("libusb-win32", "USB\\VID_054C&PID_0336 (libwdi autogenerated)"));
        assert!(is_libwdi("libwdi", ""));
        assert!(!is_libwdi("Sony", "Microsoft Windows Hardware Compatibility Publisher"));
        assert!(!is_libwdi("libusbK", "Sony Corporation"));
        assert!(!is_libwdi("PMCA-RE RELOADED", "PMCA Temporary Driver Signing"));
    }

    #[test]
    fn only_published_names_are_candidates() {
        assert!(is_published_name("oem122.inf"));
        assert!(!is_published_name("usbstor.inf"));
        assert!(!is_published_name("oem.inf"));
        assert!(!is_published_name("oem12a.inf"));
    }

    #[test]
    fn the_driver_database_is_readable_without_rights() {
        // Read-only, and machine-dependent: a clean machine has no Sony
        // packages, so the chain is checked on whatever is there.
        for (package, _) in sony_packages() {
            assert!(is_published_name(&package.published));
            assert!(package.devices.iter().all(|d| d.starts_with(r"USB\VID_054C&")));
        }
        assert!(Key::open(DEVICE_IDS).is_some());
    }
}
